import { readFileSync, writeFileSync } from "node:fs";

const sourcePath = new URL("../prisma/schema.prisma", import.meta.url);
const destinationPath = new URL("../prisma/schema.postgresql.prisma", import.meta.url);
const source = readFileSync(sourcePath, "utf8");
const generated = `// Generated mechanically from schema.prisma. Do not edit this file directly.\n${source
  .replace('output   = "../apps/api/src/generated/prisma"', 'output   = "../apps/api/src/generated/prisma-postgresql"')
  .replace('provider = "sqlite"', 'provider = "postgresql"')}`;

writeFileSync(destinationPath, generated, "utf8");
console.log("PostgreSQL Prisma schema synchronized from the SQLite source model.");
